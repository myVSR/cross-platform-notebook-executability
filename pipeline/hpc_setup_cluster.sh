#!/bin/bash
###############################################################################
# hpc_setup_cluster.sh — user-space setup of the notebook pipeline on the cluster (no root)
#
# Fixes the blockers found by pipeline/hpc_preflight.sh (notes/hpc/):
#   jq missing on compute nodes      -> static jq 1.7.1 in $NBF_HOME/bin
#   python3 is 3.9 (Intel Python)    -> pipeline venv from module anaconda3/2024.10 (Python 3.12)
#                                       with the pipeline's requirements.txt
#   pyenv Pythons lack sqlite3       -> SQLite 3.46.1 built into $NBF_HOME/opt/sqlite; env.sh
#                                       exports CPPFLAGS/LDFLAGS(+rpath)/PKG_CONFIG_PATH so that
#                                       every Python pyenv builds (also later, during runs) has it
#   pyenv missing                    -> cloned into $PYENV_ROOT (default ~/.pyenv)
# readline headers are also missing; that only affects interactive Python and is left as is.
#
# Usage (login node; needs internet, ~10-20 minutes; safe to run again):
#   bash pipeline/hpc_setup_cluster.sh
#   source ~/.notebookfair/env.sh            # in every job / shell that runs the pipeline
#   srun --time=00:45:00 --cpus-per-task=2 --mem=4G --pty bash -c \
#        'source ~/.notebookfair/env.sh && bash pipeline/hpc_preflight.sh --build-python'
#
# Settings: PROJECT_ROOT (repository checkout; default: the folder above this script),
#           NBF_HOME (default ~/.notebookfair), PYENV_ROOT (default ~/.pyenv),
#           ANACONDA_MODULE (default anaconda3/2024.10), PIPELINE_PYTHON (a python >= 3.11 to use
#           instead of the module, e.g. on a machine without modules).
# Writes a log: $NBF_HOME/setup.log
###############################################################################
set -uo pipefail

# the repository checkout (requirements.txt); default: the folder above this script
PROJECT_ROOT="${PROJECT_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
NBF_HOME="${NBF_HOME:-$HOME/.notebookfair}"
PYENV_ROOT="${PYENV_ROOT:-$HOME/.pyenv}"
ANACONDA_MODULE="${ANACONDA_MODULE:-anaconda3/2024.10}"
JQ_VERSION=1.7.1
SQLITE_VERSION=3460100            # 3.46.1
SQLITE_YEAR=2024

mkdir -p "$NBF_HOME/bin" "$NBF_HOME/opt" "$NBF_HOME/src"
LOG="$NBF_HOME/setup.log"
exec > >(tee -a "$LOG") 2>&1
echo "== hpc_setup_cluster.sh $(date -Iseconds) on $(hostname)"
step() { printf '\n-- %s\n' "$*"; }
die() { echo "[ERROR] $*"; exit 1; }

if [ ! -f "$PROJECT_ROOT/requirements.txt" ]; then
    if [ -f "$PWD/requirements.txt" ] && [ -f "$PWD/pipeline/hpc_setup_cluster.sh" ]; then
        PROJECT_ROOT="$PWD"
    else
        die "repository not found at $PROJECT_ROOT (no requirements.txt). Run the script from the repository checkout,
        e.g.  cd ~/notebook-study && bash pipeline/hpc_setup_cluster.sh
        or set PROJECT_ROOT=/path/to/notebook-study"
    fi
fi
echo "repository: $PROJECT_ROOT"

###############################################################################
step "1. jq $JQ_VERSION (static binary)"
if "$NBF_HOME/bin/jq" --version 2>/dev/null | grep -q "$JQ_VERSION"; then
    echo "already installed: $("$NBF_HOME/bin/jq" --version)"
else
    curl -fsSL -o "$NBF_HOME/bin/jq" \
        "https://github.com/jqlang/jq/releases/download/jq-$JQ_VERSION/jq-linux-amd64" || die "jq download failed"
    chmod +x "$NBF_HOME/bin/jq"
    "$NBF_HOME/bin/jq" --version || die "jq does not run"
fi
echo "sha256: $(sha256sum "$NBF_HOME/bin/jq" | cut -d' ' -f1)"

###############################################################################
step "2. SQLite $SQLITE_VERSION (library and headers for Python builds)"
SQLITE_PREFIX="$NBF_HOME/opt/sqlite"
if [ -f "$SQLITE_PREFIX/include/sqlite3.h" ] && [ -f "$SQLITE_PREFIX/lib/libsqlite3.so" ]; then
    echo "already installed in $SQLITE_PREFIX"
else
    archive="$NBF_HOME/src/sqlite-autoconf-$SQLITE_VERSION.tar.gz"
    curl -fsSL -o "$archive" "https://www.sqlite.org/$SQLITE_YEAR/sqlite-autoconf-$SQLITE_VERSION.tar.gz" ||
        die "SQLite download failed"
    echo "sha256: $(sha256sum "$archive" | cut -d' ' -f1)"
    rm -rf "$NBF_HOME/src/sqlite-autoconf-$SQLITE_VERSION"
    tar -xzf "$archive" -C "$NBF_HOME/src"
    (
        cd "$NBF_HOME/src/sqlite-autoconf-$SQLITE_VERSION" &&
        CFLAGS="-O2 -DSQLITE_ENABLE_FTS5 -DSQLITE_ENABLE_JSON1 -DSQLITE_ENABLE_RTREE -DSQLITE_ENABLE_COLUMN_METADATA" \
            ./configure --prefix="$SQLITE_PREFIX" --enable-shared --disable-static >/dev/null &&
        make -j"$(nproc)" >/dev/null && make install >/dev/null
    ) || die "SQLite build failed (see $LOG)"
fi
"$SQLITE_PREFIX/bin/sqlite3" --version

###############################################################################
step "3. env.sh (sourced by every job)"
cat > "$NBF_HOME/env.sh" <<ENV
# Generated by pipeline/hpc_setup_cluster.sh on $(date -Iseconds). Source before running the pipeline.
if command -v module >/dev/null 2>&1 || type module >/dev/null 2>&1; then
    module load $ANACONDA_MODULE >/dev/null 2>&1 || true
fi
export NBF_HOME="$NBF_HOME"
export PYENV_ROOT="$PYENV_ROOT"
export PATH="$NBF_HOME/pipeline-venv/bin:$NBF_HOME/bin:$SQLITE_PREFIX/bin:$PYENV_ROOT/bin:$PYENV_ROOT/shims:\$PATH"
# SQLite for every Python that pyenv builds (configure, setup.py and the runtime path via rpath)
export CPPFLAGS="-I$SQLITE_PREFIX/include \${CPPFLAGS:-}"
export LDFLAGS="-L$SQLITE_PREFIX/lib -Wl,-rpath,$SQLITE_PREFIX/lib \${LDFLAGS:-}"
export PKG_CONFIG_PATH="$SQLITE_PREFIX/lib/pkgconfig\${PKG_CONFIG_PATH:+:\$PKG_CONFIG_PATH}"
export CPATH="$SQLITE_PREFIX/include\${CPATH:+:\$CPATH}"
export LIBRARY_PATH="$SQLITE_PREFIX/lib\${LIBRARY_PATH:+:\$LIBRARY_PATH}"
# pip cache and tool environment on the shared file system; venvs go to node-local scratch
export PIP_CACHE_DIR="$NBF_HOME/pip-cache"
export TOOL_ENV_DIR="$NBF_HOME/tool-env"
export VENV_BASE_DIR="\${SLURM_TMPDIR:-\${TMPDIR:-/tmp}}/nbf-venvs-\${USER}"
export NBF_ENV_LOADED=1
ENV
echo "written: $NBF_HOME/env.sh"
# shellcheck disable=SC1091
source "$NBF_HOME/env.sh"

###############################################################################
step "4. pyenv"
if [ -x "$PYENV_ROOT/bin/pyenv" ]; then
    echo "already installed: $("$PYENV_ROOT/bin/pyenv" --version)"
else
    git clone -q --depth 1 https://github.com/pyenv/pyenv.git "$PYENV_ROOT" || die "pyenv clone failed"
    echo "installed: $("$PYENV_ROOT/bin/pyenv" --version) (commit $(git -C "$PYENV_ROOT" rev-parse --short HEAD))"
fi

###############################################################################
step "5. Pipeline Python environment ($NBF_HOME/pipeline-venv)"
base="${PIPELINE_PYTHON:-}"
if [ -z "$base" ]; then
    for candidate in python3.12 python3.11 python3; do
        if command -v "$candidate" >/dev/null 2>&1 &&
           "$candidate" -c 'import sys; sys.exit(sys.version_info < (3, 11))' 2>/dev/null; then
            base=$(command -v "$candidate"); break
        fi
    done
fi
[ -n "$base" ] || die "no Python >= 3.11 found (load $ANACONDA_MODULE or set PIPELINE_PYTHON)"
echo "base interpreter: $base ($("$base" --version 2>&1))"
if [ ! -x "$NBF_HOME/pipeline-venv/bin/python" ]; then
    "$base" -m venv "$NBF_HOME/pipeline-venv" || die "venv creation failed"
fi
"$NBF_HOME/pipeline-venv/bin/python" -m pip install -q --upgrade pip ||
    die "pip upgrade failed (internet/proxy?)"
"$NBF_HOME/pipeline-venv/bin/python" -m pip install -q -r "$PROJECT_ROOT/requirements.txt" ||
    die "installing requirements.txt failed (see $LOG)"
"$NBF_HOME/pipeline-venv/bin/python" -c 'import nbformat, nbconvert, nbdime, numpy, PIL, IPython, tomllib, sqlite3; print("pipeline packages import fine")' ||
    die "pipeline packages do not import"

###############################################################################
step "6. Check"
hash -r
for tool in jq sqlite3 python3 pyenv; do
    printf '  %-8s %s  %s\n' "$tool" "$(command -v "$tool")" "$("$tool" --version 2>&1 | head -1)"
done
echo
echo "Done. In every job or shell that runs the pipeline:  source $NBF_HOME/env.sh"
echo "Next: run the preflight again on a compute node with --build-python (see the header)."
